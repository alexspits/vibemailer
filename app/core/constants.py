"""Константы, не зависящие от конфигурации."""

import re

# Проверка синтаксиса email (без проверки MX — только формат).
EMAIL_RE = re.compile(r"^[^@\s]+@[^@\s]+\.[^@\s]+$")

# Ключ сервера. Он уезжает в имена вложений (`alice-1_ru.conf`) и в адреса ручек, а
# заводится теперь из интерфейса — поэтому набор символов ограничен явно.
SERVER_KEY_RE = re.compile(r"^[a-z0-9][a-z0-9_-]*$")
